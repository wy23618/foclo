// Generate tablet-only equivalents of native rpx declarations. The original
// phone stylesheet stays byte-for-byte unchanged above the generated section.
// Run after editing WXSS: node scripts/build-tablet-styles.js
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const START = '/* tablet-generated:start */';
const END = '/* tablet-generated:end */';
const TABLET = '(min-width:500px) and (min-device-width:520px) and (min-device-height:520px)';

function blocks(source) {
  source = source.replace(/\/\*[\s\S]*?\*\//g, '').replace(/@import\s+[^;]+;/g, '');
  const result = [];
  let start = 0, depth = 0, quote = '', body = 0;
  for (let i = 0; i < source.length; i++) {
    const ch = source[i];
    if (quote) { if (ch === quote && source[i - 1] !== '\\') quote = ''; continue; }
    if (ch === '"' || ch === "'") { quote = ch; continue; }
    if (ch === '{') { if (depth++ === 0) body = i; }
    if (ch === '}' && --depth === 0) {
      result.push([source.slice(start, body).trim(), source.slice(body + 1, i)]);
      start = i + 1;
    }
  }
  return result;
}

function pixels(source) {
  return source.replace(/(-?(?:\d*\.)?\d+)rpx/g, (_, n) => `${Math.round(Number(n) * .6 * 1000) / 1000}px`);
}

function generate(source, media = '') {
  const groups = [];
  const add = (condition, rule) => {
    const last = groups[groups.length - 1];
    if (last && last[0] === condition) last[1] += rule + '\n';
    else groups.push([condition, rule + '\n']);
  };
  for (const [selector, body] of blocks(source)) {
    if (selector.startsWith('@media')) {
      const condition = selector.slice(6).trim();
      const nested = generate(body, media ? `${media} and ${condition}` : condition);
      for (const [key, value] of nested) add(key, value.trim());
    } else if (/^@(?:-webkit-)?keyframes\b/.test(selector)) {
      add(media, `${selector}{${pixels(body)}}`);
    } else {
      // Copy complete rules, including non-rpx resets. Copying just lengths
      // would let an earlier rpx rule override a later percentage/zero reset.
      add(media, `${selector}{${pixels(body.trim())}}`);
    }
  }
  return groups;
}

function build(source) {
  const parts = source.split(START);
  const base = parts[0];
  if (!/\d+rpx/.test(base)) return source;
  const custom = parts.length > 1 ? parts[1].split(END)[1] || '' : '';
  const newline = base.includes('\r\n') ? '\r\n' : '\n';
  const generated = [...generate(base)].map(([media, body]) => `@media ${TABLET}${media ? ' and ' + media : ''}{\n${body}}`).join('\n').replace(/[\t ]+$/gm, '');
  if (!generated) return source;
  return `${base}${START}${newline}/* Generated by scripts/build-tablet-styles.js; edit the original rules above. */${newline}${generated.replace(/\r?\n/g, newline)}${newline}${END}${custom}`;
}

function files(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(item => {
    const file = path.join(dir, item.name);
    return item.isDirectory() ? files(file) : file.endsWith('.wxss') ? [file] : [];
  });
}

if (require.main === module) {
  for (const file of [path.join(root, 'app.wxss'), ...files(path.join(root, 'pages')), ...files(path.join(root, 'components'))]) {
    const source = fs.readFileSync(file, 'utf8'), output = build(source);
    if (source !== output) fs.writeFileSync(file, output);
  }
}
module.exports = { build, generate, START, END, TABLET };
